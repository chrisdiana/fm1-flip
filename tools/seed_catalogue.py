#!/usr/bin/env python3
"""Generate an offline firmware metadata seed from an existing validated cache.

Never requests the Hub or downloads firmware/artwork. The embedded snapshot is
attributed and dated; it is not a substitute for daily network refreshes.
"""
import argparse,json
from pathlib import Path
from sync_catalogue import _validate_catalogue,CATALOGUE_URL,CATALOGUE_LICENSE
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--cache',type=Path,default=ROOT/'.cache/catalogue-cache.json')
a=p.parse_args()
cache=json.loads(a.cache.read_text())
entries=_validate_catalogue(cache['catalogue'])
payload={'schemaVersion':1,'sourceUrl':CATALOGUE_URL,'retrievedAt':cache['fetched_at'],
 'attribution':'Firmware list: The Firmware Hub – https://thefirmwarehub.com',
 'license':CATALOGUE_LICENSE,'status':'bundled-offline-snapshot',
 'totalEntries':len(entries),'entries':entries}
data=json.dumps(payload,ensure_ascii=False,separators=(',',':'))
assert ')FM1SEED"' not in data
rows=[]
for entry in entries:
    fields=[entry['id'],entry.get('sha256') or '',entry.get('artworkUrl') or '']
    rows.append(' {'+','.join(json.dumps(v) for v in fields)+','+str(entry.get('hubInstalls') or 0)+','+('true' if entry.get('hubInstalls') is not None else 'false')+'}')
metadata='''
struct PresentationSeed { const char* id; const char* hash; const char* artwork; uint32_t popularity; bool known; };
static const PresentationSeed Presentation[] PROGMEM = {
'''+',\n'.join(rows)+'''};
void enrichBundledPresentation(JsonObject entry) {
 if(entry.isNull())return;
 const bool countMissing=!entry.containsKey("hubInstalls"),artMissing=!entry.containsKey("artworkUrl");
 if(!countMissing&&!artMissing)return;
 const char* id=entry["id"]|"";const char* hash=entry["sha256"]|"";
 if(!*id)return;
 for(const auto& seed:Presentation) {
  if(strcmp(id,seed.id)||strcmp(hash,seed.hash))continue;
  if(countMissing){if(seed.known)entry["hubInstalls"]=seed.popularity;else entry["hubInstalls"]=nullptr;}
  if(artMissing){if(*seed.artwork){entry["artworkUrl"]=seed.artwork;entry["artworkKind"]="hub-card";}else entry["artworkUrl"]=nullptr;}
  entry["presentationSeeded"]=true;return;
 }
}
'''
source='''// Generated by tools/seed_catalogue.py from the attributed cached feed.
// Metadata only; no firmware packages or image bytes are embedded.
#include "device/catalogue_seed.h"
#include <Arduino.h>
#include <cstring>
namespace device {
static const char Seed[] PROGMEM = R"FM1SEED('''+data+''')FM1SEED";
'''+metadata+'''
bool ensureBundledCatalogue(fs::FS& filesystem) {
 if(filesystem.exists("/fm1/catalogue.json"))return true;
 if(!filesystem.exists("/fm1")&&!filesystem.mkdir("/fm1"))return false;
 const char* pending="/fm1/catalogue.seed.part";
 File out=filesystem.open(pending,FILE_WRITE);
 if(!out)return false;
 const size_t bytes=sizeof Seed-1;
 for(size_t offset=0;offset<bytes;offset+=1024) {
  const size_t count=bytes-offset<1024?bytes-offset:1024;
  if(out.write(reinterpret_cast<const uint8_t*>(Seed+offset),count)!=count) {
   out.close();filesystem.remove(pending);return false;
  }
  delay(1);
 }
 out.flush();out.close();
 if(filesystem.exists("/fm1/catalogue.json")){filesystem.remove(pending);return true;}
 if(!filesystem.rename(pending,"/fm1/catalogue.json")){filesystem.remove(pending);return false;}
 return true;
}
}
'''
target=ROOT/'src/device/catalogue_seed.cpp'
target.write_text(source)
print(f'Embedded {len(entries)} attributed metadata records ({len(data.encode())} bytes); no network used')
